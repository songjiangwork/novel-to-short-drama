"""Issue #128 source/prompt regression contract, with no provider invocation.

This test verifies only the tracked Alice source, the saved bad-candidate
description, and the v5 prompt instruction. It deliberately does not treat a
prompt as proof of future Qwen behavior.
"""

from __future__ import annotations

import json

from short_drama.llm import PromptRegistry
from short_drama.paths import REPO_ROOT
from short_drama.story.source import extract_txt_structure


FIXTURE_PATH = REPO_ROOT / "tests" / "fixtures" / "a3_issue_128_ch009_c001_cand_rel_009.json"
ALICE_SOURCE_PATH = REPO_ROOT / "examples" / "a3e_real_novel" / "source" / "novel.txt"
PROMPTS_DIR = REPO_ROOT / "prompts" / "story"


def _fixture() -> dict:
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


def _source_paragraphs() -> dict[str, str]:
    chapters, _encoding, _parser_version = extract_txt_structure(
        ALICE_SOURCE_PATH.read_bytes()
    )
    return {
        paragraph.paragraph_id: paragraph.text_original
        for chapter in chapters
        for paragraph in chapter.paragraphs
    }


def test_issue_128_fixture_is_exactly_backed_by_tracked_alice_source():
    """The fixture pins the actual three-paragraph CH009 source context."""
    fixture = _fixture()
    source = _source_paragraphs()

    assert fixture["chunk_id"] == "CH009_C001"
    for paragraph in fixture["source_paragraphs"]:
        assert source[paragraph["paragraph_id"]] == paragraph["text_original"]

    assert "The master was an old Turtle—we used to call him Tortoise—" in source[
        "CH009_P0055"
    ]
    assert source["CH009_P0056"].endswith("Alice asked.")
    evidence = fixture["primary_evidence"]
    assert evidence["paragraph_id"] == "CH009_P0057"
    assert evidence["role"] == "primary"
    assert evidence["strength"] == "explicit"
    assert evidence["excerpt"] == source[evidence["paragraph_id"]]
    assert "because he taught us" in evidence["excerpt"]


def test_issue_128_fixture_distinguishes_reported_endpoints_from_listener():
    """The source interpretation is a regression oracle, not a model result."""
    fixture = _fixture()
    saved = fixture["saved_candidate"]
    expected = fixture["source_backed_endpoint_interpretation"]

    assert saved["candidate_id"] == "cand_rel_009"
    assert saved["source_entity_original"] == expected["source_entity_original"]
    assert saved["target_entity_original"] == "Alice"
    assert expected["target_entity_original"] == "Tortoise"
    assert expected["current_conversation_participant_not_an_endpoint_original"] == "Alice"
    assert expected["target_entity_original"] != saved["target_entity_original"]


def test_issue_128_fixture_checks_prompt_contract_not_model_behavior():
    """No real/fake Qwen output is asserted or generated by this regression."""
    fixture = _fixture()
    scope = fixture["verification_scope"]
    prompt = PromptRegistry(PROMPTS_DIR).load("a3.chunk-extraction", version=5)

    assert scope == {
        "source_evidence": "verified_against_tracked_alice_source",
        "prompt_instruction": "verified_against_a3_prompt_v5",
        "model_behavior": "not_verified_no_provider_call",
    }
    assert "RELATIONSHIP ENDPOINT ATTRIBUTION" in prompt.system_template
    assert "Do not substitute a current speaker, listener" in prompt.system_template
    assert "not_verified" in scope["model_behavior"]
